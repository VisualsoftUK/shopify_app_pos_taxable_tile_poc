<?php

namespace Tests;

use App\Domain\Models\User;
use Illuminate\Foundation\Testing\TestCase as BaseTestCase;
use Illuminate\Support\Facades\Http;
use Illuminate\Support\Sleep;
use Osiset\ShopifyApp\Contracts\ShopModel;
use PHPUnit\Framework\Exception;
use Tests\Concerns\MocksGraphQlOperations;
use Visualsoft\Shopify\Tests\Concerns\HasShopifyAuth;
use Visualsoft\Shopify\Tests\Concerns\HasShopifyPosAuth;
use Visualsoft\Shopify\Tests\Concerns\InteractsWithGraphQl;

abstract class TestCase extends BaseTestCase
{
    use CreatesApplication;
    use HasShopifyAuth;
    use HasShopifyPosAuth;
    use InteractsWithGraphQl;
    use MocksGraphQlOperations;

    protected function setUp(): void
    {
        parent::setUp(); // TODO: Change the autogenerated stub

        if (config('database.default') !== 'sqlite') {
            throw new Exception(sprintf('Cannot run tests using the %s database driver. It should be sqlite.',
                config('database.default')
            ));
        }

        Sleep::fake();
        Http::preventStrayRequests();
    }

    /**
     * Default admin shops have an active Mantle plan and a functional App Pricing
     * plan so the gate and shared mantlePlan use the same entitlements.
     */
    public function asShop(?ShopModel $shop = null): static
    {
        if ($shop === null) {
            $shop = User::factory()
                ->withMantlePlan()
                ->withAppPricingPlan()
                ->create();
        }

        return $this->actingAs($shop)->withShopifyAuthHeaders($shop);
    }

    protected function mockCurrencyCode()
    {
        $this->testApiHelper()
            ->getApi()
            ->shouldReceive('graph')
            ->withArgs(function (string $query, array $params = []): bool {
                return str_contains($query, 'shop') && str_contains($query, 'currencyCode');
            })
            ->zeroOrMoreTimes()
            ->andReturn([
                'body' => [
                    'data' => [
                        'shop' => [
                            'currencyCode' => 'GBP',
                        ],
                    ],
                ],
            ]);
    }

    protected function mockLocale()
    {
        $this->testApiHelper()
            ->getApi()
            ->shouldReceive('graph')
            ->withArgs(function (string $query, array $params = []): bool {
                return str_contains($query, 'shopLocales') && str_contains($query, 'locale') && str_contains($query, 'primary');
            })
            ->zeroOrMoreTimes()
            ->andReturn([
                'body' => [
                    'data' => [
                        'shopLocales' => [
                            [
                                'locale' => 'en',
                                'primary' => true,
                            ],
                        ],
                    ],
                ],
            ]);
    }
}
